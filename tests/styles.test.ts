import { readFileSync, readdirSync } from 'node:fs'
import { createRequire } from 'node:module'
import { resolve } from 'node:path'
import { expect, test } from '@lightning-js/lightning'

const readStyle = (path: string) => readFileSync(`packages/react/src/${path}`, 'utf8')

test('keeps the shared contract and non-Material adapters free of Material dependencies', () => {
  for (const path of [
    'foundation.css',
    'base.css',
    'themes/minimal.css',
    'themes/soft.css',
    'themes/brutalist.css',
  ]) {
    expect(readStyle(path)).not.toContain('--md-')
  }
  expect(readStyle('themes/clean.css')).toContain('--md-sys-color-primary')
})

test('loads base rules before independently selectable style adapters', () => {
  const bundle = readStyle('styles.css')
  const themes = readdirSync('packages/react/src/themes')
    .filter((path) => path.endsWith('.css'))
    .sort()
  const sources = ['base.css', ...themes.map((path) => `themes/${path}`)]
  const expected =
    [
      '/* Generated by scripts/generate-styles.mjs. Edit foundation/component CSS or themes instead. */',
      ...sources.map((path) => readStyle(path).trimEnd()),
    ].join('\n\n') + '\n'
  expect(bundle).toBe(expected)
  expect(bundle).not.toContain('@import')
})

test('generates the base-only entry from every neutral component source', () => {
  const components = readdirSync('packages/react/src')
    .filter(
      (path) =>
        path.endsWith('.css') && !['base.css', 'styles.css', 'foundation.css'].includes(path),
    )
    .sort()
  const expected =
    [
      '/* Generated by scripts/generate-styles.mjs. Edit foundation.css or component CSS instead. */',
      ...['foundation.css', ...components].map((path) => readStyle(path).trimEnd()),
    ].join('\n\n') + '\n'
  expect(readStyle('base.css')).toBe(expected)
  for (const path of components) expect(readStyle(path)).not.toContain('--md-')
})

test('exports a base-only entry and direct theme entries without requiring the bundle', () => {
  const manifest = JSON.parse(readFileSync('packages/react/package.json', 'utf8'))
  expect(manifest.exports['./base.css']).toBe('./src/base.css')
  expect(manifest.exports['./themes/*.css']).toBe('./src/themes/*.css')
  const fromDemo = createRequire(resolve('apps/demo/package.json'))
  for (const path of ['base.css', 'themes/soft.css']) {
    expect(readFileSync(fromDemo.resolve(`@zixiao-labs/ui-kits-react/${path}`), 'utf8')).toBe(
      readStyle(path),
    )
  }
})

test('all neutral CSS token references have a declared source', () => {
  const sources = readdirSync('packages/react/src')
    .filter((path) => path.endsWith('.css') && !['base.css', 'styles.css'].includes(path))
    .map(readStyle)
    .join('\n')
  const defined = new Set([...sources.matchAll(/(--zx-[\w-]+)\s*:/g)].map((match) => match[1]))
  const used = new Set([...sources.matchAll(/var\((--zx-[\w-]+)/g)].map((match) => match[1]))
  expect([...used].filter((token) => !defined.has(token))).toEqual([])
})

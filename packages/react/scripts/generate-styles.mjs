import { readFile, readdir, writeFile } from 'node:fs/promises'

// Both public entries are flat: Nasti's dev CSS injection does not resolve
// relative CSS @imports. Component sources and theme adapters stay independent.
const source = new URL('../src/', import.meta.url)
const themes = (await readdir(new URL('themes/', source)))
  .filter((path) => path.endsWith('.css'))
  .sort()
const components = (await readdir(source))
  .filter(
    (path) => path.endsWith('.css') && !['base.css', 'styles.css', 'foundation.css'].includes(path),
  )
  .sort()
const baseSources = ['foundation.css', ...components]
const base =
  [
    '/* Generated by scripts/generate-styles.mjs. Edit foundation.css or component CSS instead. */',
    ...(await Promise.all(baseSources.map((path) => readFile(new URL(path, source), 'utf8')))).map(
      (style) => style.trimEnd(),
    ),
  ].join('\n\n') + '\n'
await writeFile(new URL('base.css', source), base)
const styles = await Promise.all(
  themes.map((path) => readFile(new URL(`themes/${path}`, source), 'utf8')),
)
const bundle =
  [
    '/* Generated by scripts/generate-styles.mjs. Edit foundation/component CSS or themes instead. */',
    base.trimEnd(),
    ...styles.map((style) => style.trimEnd()),
  ].join('\n\n') + '\n'

await writeFile(new URL('styles.css', source), bundle)

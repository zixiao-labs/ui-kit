import { readFile, writeFile } from 'node:fs/promises'
import { prepareShader } from '@vgpu/wgsl/prepare'

// Nasti has no WGSL loader. Prepare once here, never ship the parser to browsers.
const source = new URL('../src/shadow.wgsl', import.meta.url)
const shader = prepareShader(await readFile(source, 'utf8'), 'shadow.wgsl')
await writeFile(
  new URL('../src/shadow.shader.ts', import.meta.url),
  `// Generated by scripts/generate-shadow.mjs. Edit shadow.wgsl instead.\nimport type { ShaderSource } from '@vgpu/wgsl'\nexport default ${JSON.stringify(shader, null, 2)} satisfies ShaderSource\n`,
)

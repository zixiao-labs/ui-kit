import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { promisify } from 'node:util'

// Authoring tool only. Install Potrace outside the dependency graph and expose
// it via NODE_PATH; neither it nor ImageMagick is needed to build/use the kit.
// See docs/pattern-tracing.md for the source, crops and exact invocation.
const require = createRequire(import.meta.url)
const trace = promisify(require('potrace').trace)
const input = process.argv[2]
if (!input) throw new Error('Usage: node trace-patterns.mjs <1216x2688 reference JPEG>')
const dimensions = execFileSync('magick', ['identify', '-format', '%wx%h', input], {
  encoding: 'utf8',
})
if (dimensions !== '1216x2688') throw new Error(`Unexpected reference dimensions: ${dimensions}`)
const hash = createHash('sha256')
  .update(await readFile(input))
  .digest('hex')
const assets = new URL('../assets/patterns/', import.meta.url)
const fixtures = new URL('../tests/fixtures/patterns/', import.meta.url)
const scratch = resolve('.oil-ui/pattern-trace')
await Promise.all([
  mkdir(assets, { recursive: true }),
  mkdir(fixtures, { recursive: true }),
  mkdir(scratch, { recursive: true }),
])

// hui/lei: measured internal periods with matching straight cross-sections.
// yunlei: preserve the complete irregular cloud band and its original ends;
// it is not an alternation of a square glyph and a rounded glyph.
const crops = {
  hui: { x: 432, y: 1894, width: 120, height: 104, periodic: true },
  yunlei: { x: 190, y: 1552, width: 948, height: 196, periodic: false },
  lei: { x: 538, y: 1258, width: 219, height: 188, periodic: true },
}
const motifs = {}
for (const [name, crop] of Object.entries(crops)) {
  const png = new URL(`${name}.png`, fixtures)
  const pngPath = fileURLToPath(png)
  execFileSync('magick', [
    input,
    '-crop',
    `${crop.width}x${crop.height}+${crop.x}+${crop.y}`,
    '+repage',
    '-colorspace',
    'Gray',
    '-threshold',
    '65%',
    // Close tiny paper/print speckles inside the ink, not the spaces between turns.
    '-negate',
    '-morphology',
    'Close',
    'Disk:1',
    '-negate',
    '-strip',
    `PNG32:${pngPath}`,
  ])
  let bitmap = pngPath
  if (crop.periodic) {
    // Trace three copies, then display the middle one. Potrace must not round
    // off a cut stroke at the tile edge and introduce a gap when repeated.
    bitmap = resolve(scratch, `${name}-tripled.png`)
    execFileSync('magick', [pngPath, pngPath, pngPath, '+append', `PNG32:${bitmap}`])
  }
  const svg = await trace(bitmap, {
    threshold: 128,
    turdSize: 8,
    alphaMax: 1,
    optTolerance: 0.5,
    color: 'currentColor',
  })
  const path = svg.match(/<path d="([^"]+)"/)?.[1]
  if (!path) throw new Error(`Potrace produced no path for ${name}`)
  const offsetX = crop.periodic ? crop.width : 0
  motifs[name] = { width: crop.width, height: crop.height, offsetX, path }
  await writeFile(
    new URL(`${name}.svg`, assets),
    `<svg xmlns="http://www.w3.org/2000/svg" width="${crop.width}" height="${crop.height}" viewBox="${offsetX} 0 ${crop.width} ${crop.height}">\n` +
      `  <!-- Traced from the supplied reference; source SHA-256 ${hash}. -->\n` +
      // viewBox alone does not clip its letterboxed margins when resized.
      `  <defs><clipPath id="${name}-crop"><rect x="${offsetX}" width="${crop.width}" height="${crop.height}"/></clipPath></defs>\n` +
      `  <path d="${path}" fill="currentColor" fill-rule="evenodd" clip-path="url(#${name}-crop)"/>\n</svg>\n`,
  )
}
await writeFile(
  new URL('../src/optional/pattern-traces.ts', import.meta.url),
  `// Generated by scripts/trace-patterns.mjs; do not redraw these contours by hand.\n` +
    `// Source SHA-256: ${hash}\n` +
    `export const patternTraces = ${JSON.stringify(motifs, null, 2)} as const\n`,
)
console.log(
  `Traced three patterns from ${hash}; generated SVGs, reference masks and pattern-traces.ts`,
)
